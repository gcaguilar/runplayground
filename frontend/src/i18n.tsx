const messages: Record<Locale, Record<MessageKey, string>> = { es, en };

export type Locale = "es" | "en";
export type Units = "metric" | "imperial";

const LOCALE_KEY = "run.locale";
const UNITS_KEY = "run.units";

function readLocale(): Locale {
  const stored = localStorage.getItem(LOCALE_KEY);
  if (stored === "es" || stored === "en") return stored;
  return "es";
}

function readUnits(): Units {
  return localStorage.getItem(UNITS_KEY) === "imperial" ? "imperial" : "metric";
}

type I18nValue = {
  locale: Locale;
  units: Units;
  setLocale: (locale: Locale) => void;
  setUnits: (units: Units) => void;
  t: (key: MessageKey, values?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(readLocale);
  const [units, setUnitsState] = useState<Units>(readUnits);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const setLocale = useCallback((next: Locale) => {
    localStorage.setItem(LOCALE_KEY, next);
    setLocaleState(next);
  }, []);

  const setUnits = useCallback((next: Units) => {
    localStorage.setItem(UNITS_KEY, next);
    setUnitsState(next);
  }, []);

  const t = useCallback(
    (key: MessageKey, values?: Record<string, string | number>) => {
      let message = messages[locale][key] ?? messages.es[key] ?? key;
      if (values) {
        for (const [name, value] of Object.entries(values)) {
          message = message.replaceAll(`{${name}}`, String(value));
        }
      }
      return message;
    },
    [locale],
  );

  const value = useMemo(
    () => ({ locale, units, setLocale, setUnits, t }),
    [locale, units, setLocale, setUnits, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}

export function localeTag(locale: Locale): string {
  return locale === "es" ? "es-ES" : "en-US";
}
